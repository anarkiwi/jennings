"""Generate ``crates/jennings-core/src/flow_gen.rs`` from :func:`jennings.dataflow.flow`.

Each opcode's flow is read on symbolic locations (registers, operand bytes ``O1``/``O2``, loads
``L0``... and stores ``S0``...) into bit masks of each output's and each access address's inputs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from deity_informant.lifter import template

from jennings.dataflow import REGISTERS, flow

OUT = Path(__file__).resolve().parent.parent / "crates/jennings-core/src/flow_gen.rs"
PC, BASE = 0x1000, 0x5AC3
O1, O2, LOAD0, STORE0, PCOUT = 16, 17, 20, 16, 31
REG = {name: i for i, name in REGISTERS.items()}
KIND = {
    "next": "Next",
    "br": "Branch",
    "jmp": "Jmp",
    "jsr": "Jsr",
    "jmpind": "JmpInd",
    "rts": "Rts",
    "rti": "Rti",
    "brk": "Brk",
    "jam": "Jam",
}


def _bit(sym):
    if sym in REG:
        return REG[sym]
    if sym in ("O1", "O2"):
        return O1 if sym == "O1" else O2
    assert sym[0] == "L", sym
    return LOAD0 + int(sym[1:])


def _mask(syms):
    m = 0
    for s in syms:
        m |= 1 << _bit(s)
    return m


def opcode_flow(op):
    """``(kind, len, loads, stores, outs, load_addrs, store_addrs)`` of opcode ``op``; ``outs`` is
    ``[(dst, mask)]``, ``dst`` a register index, ``16 + k`` for store ``k`` or 31 for a branch's
    condition."""
    mem = bytearray(0x10000)
    mem[PC : PC + 3] = bytes((op, BASE & 0xFF, BASE >> 8))
    addrs = []
    out = flow(
        mem,
        PC,
        ["L%d" % k for k in range(8)],
        ["S%d" % k for k in range(8)],
        {1: "O1", 2: "O2"},
        addrs,
    )
    outs = []
    for dst, ins in out.items():
        if dst == "PC":
            code = PCOUT
        elif dst in REG:
            code = REG[dst]
        else:
            code = STORE0 + int(dst[1:])
        outs.append((code, _mask(ins)))
    loads = [m for store, _a, m in addrs if not store]
    stores = [m for store, _a, m in addrs if store]
    t = template(op)
    return (
        KIND[t.ctrl[0]],
        t.len,
        len(loads),
        len(stores),
        sorted(outs),
        [_mask(m) for m in loads],
        [_mask(m) for m in stores],
    )


HEADER = """\
// Generated by tools/gen_flow.py from jennings.dataflow; do not edit.

use crate::taint::{Flow, Kind};

pub(crate) static FLOW: [Flow; 256] = [
"""


def _words(v):
    return "&[%s]" % ", ".join("0x%x" % m for m in v)


def generate() -> str:
    out = [HEADER]
    for op in range(256):
        kind, n, nl, ns, outs, la, sa = opcode_flow(op)
        out.append(
            "    Flow { kind: Kind::%s, len: %d, loads: %d, stores: %d, outs: &[%s], load_addr: %s, "
            "store_addr: %s }, // %02X\n"
            % (
                kind,
                n,
                nl,
                ns,
                ", ".join("(%d, 0x%x)" % o for o in outs),
                _words(la),
                _words(sa),
                op,
            )
        )
    out.append("];\n")
    return "".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the checked-in file is stale")
    args = ap.parse_args(argv)
    src = generate()
    if args.check:
        if OUT.read_text() != src:
            print("%s is stale; run tools/gen_flow.py" % OUT, file=sys.stderr)
            return 1
        return 0
    OUT.write_text(src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
